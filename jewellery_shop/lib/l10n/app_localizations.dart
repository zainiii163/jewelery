class AppLocalizations {
  final Locale locale;
  AppLocalizations(this.locale);

  static bool isRTL(Locale locale) => locale.languageCode == 'ur';

  Map<String, String> get _dict =>
      locale.languageCode == 'ur' ? AppStrings.ur : AppStrings.en;

  String t(String key) => _dict[key] ?? key;

  // Helper for number formatting
  String formatMoney(double value, String currency) {
    final s = value.toStringAsFixed(0);
    // add comma separators
    final buf = StringBuffer();
    String n = s;
    if (n.startsWith('-')) {
      buf.write('-');
      n = n.substring(1);
    }
    final len = n.length;
    for (int i = 0; i < len; i++) {
      buf.write(n[i]);
      final rem = len - i - 1;
      if (rem > 0 && rem % 3 == 0) {
        buf.write(',');
      }
    }
    if (locale.languageCode == 'ur') {
      return '${buf.toString()} $currency';
    }
    return '$currency ${buf.toString()}';
  }

  String formatWeight(double value) {
    return value.toStringAsFixed(3);
  }

  String formatKg(double value) {
    return value.toStringAsFixed(3);
  }
}
